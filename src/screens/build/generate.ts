import fs from 'fs-extra';
import path from 'path';
import type { ScreenManifestEntry, ScreensManifest } from '../manifest';
import { readScreenMeta } from './analyze';
import { checkScreen, ScreenBuildError } from './check';
import { resolveScreenDeclarations, type ScreenFiles } from './declarations';

/**
 * Writes the four files that compile a workspace's screens into the docs app:
 *
 * - `generated/screens.json`: the manifest (titles, icons, access, collections, tools). The nav, the
 *   landing route and the API routes read it.
 * - `generated/screens.client.ts`: one lazy import per screen UI, so each screen is its own chunk.
 * - `generated/screens.server.ts`: the collections and tools modules. Only API routes import it, so
 *   server code never reaches the browser bundle.
 * - `generated/screens.css`: a Tailwind `@source` per screen directory or screen package. Tailwind
 *   scans only the app, and the screens live in the workspace or in `node_modules`.
 *
 * The generated files import screens by resolved file path, not by package name. The staged app
 * sits inside the `handoff-app` package, where workspace packages may not resolve.
 */

export const SCREENS_MANIFEST_PATH = path.join('generated', 'screens.json');
export const SCREENS_CLIENT_PATH = path.join('generated', 'screens.client.ts');
export const SCREENS_SERVER_PATH = path.join('generated', 'screens.server.ts');
export const SCREENS_STYLES_PATH = path.join('generated', 'screens.css');

export const SCREENS_GENERATED_FILES = [SCREENS_MANIFEST_PATH, SCREENS_CLIENT_PATH, SCREENS_SERVER_PATH, SCREENS_STYLES_PATH];

export const DEFAULT_SCREENS_TITLE = 'Tools';

export type { ScreenManifestEntry, ScreensManifest };

export interface ScreensContext {
  workingPath: string;
  modulePath: string;
  config: { screens?: unknown; app?: { screensTitle?: string } };
}

/** Resolve, check and describe every declared screen. Throws {@link ScreenBuildError} with all problems. */
export const readScreens = async (context: ScreensContext): Promise<{ files: ScreenFiles[]; manifest: ScreensManifest }> => {
  let files: ScreenFiles[];
  try {
    files = resolveScreenDeclarations(context.config.screens, context.workingPath);
  } catch (error) {
    throw new ScreenBuildError((error as Error).message);
  }

  const searchPaths = [context.workingPath, context.modulePath];
  const problems: string[] = [];
  const screens: ScreenManifestEntry[] = [];
  for (const screen of files) {
    try {
      const meta = readScreenMeta(screen.ui, searchPaths);
      const { collections, tools, options } = await checkScreen(screen, context.workingPath);
      screens.push({ id: screen.id, ...meta, collections, tools, options, needsServer: collections.length > 0 || tools.length > 0 });
    } catch (error) {
      problems.push((error as Error).message);
    }
  }
  if (problems.length > 0) throw new ScreenBuildError(problems.join('\n'));

  screens.sort((a, b) => a.nav.weight - b.nav.weight || a.title.localeCompare(b.title));
  return { files, manifest: { title: context.config.app?.screensTitle?.trim() || DEFAULT_SCREENS_TITLE, screens } };
};

const relativePath = (from: string, target: string): string => {
  const relative = path.relative(from, target).split(path.sep).join('/');
  return relative.startsWith('.') ? relative : `./${relative}`;
};

/** Without the extension: the app's type check rejects `.ts`/`.tsx` endings in imports. */
const importPath = (from: string, file: string): string => relativePath(from, file).replace(/\.[cm]?[jt]sx?$/, '');

const HEADER = '// Generated by the Handoff build from the `screens` config. Do not edit.\n';

const clientSource = (files: ScreenFiles[], generatedDir: string): string =>
  `${HEADER}import type { ScreenLoaders } from '@/lib/screens/types';

export const screenLoaders: ScreenLoaders = {
${files.map((screen) => `  ${JSON.stringify(screen.id)}: () => import(${JSON.stringify(importPath(generatedDir, screen.ui))}),`).join('\n')}
};
`;

const serverSource = (files: ScreenFiles[], generatedDir: string): string => {
  const imports: string[] = [];
  const entries = files.map((screen, index) => {
    const parts: string[] = [];
    if (screen.collections) {
      imports.push(`import * as collections${index} from ${JSON.stringify(importPath(generatedDir, screen.collections))};`);
      parts.push(`collections: collections${index}`);
    }
    if (screen.tools) {
      imports.push(`import tools${index} from ${JSON.stringify(importPath(generatedDir, screen.tools))};`);
      parts.push(`tools: tools${index}`);
    }
    return `  ${JSON.stringify(screen.id)}: { ${parts.join(', ')} },`;
  });
  return `${HEADER}import type { ScreenServerModules } from '@/lib/screens/types';
${imports.join('\n')}

export const screenServerModules: ScreenServerModules = {
${entries.join('\n')}
};
`;
};

const stylesSource = (files: ScreenFiles[], generatedDir: string): string =>
  `/* Generated by the Handoff build from the \`screens\` config. Do not edit. */\n${files
    .map((screen) => `@source ${JSON.stringify(relativePath(generatedDir, screen.dir))};`)
    .join('\n')}\n`;

/** Write a file only when its content changed, so the dev server does not reload for nothing. */
const writeIfChanged = async (file: string, content: string): Promise<boolean> => {
  if ((await fs.pathExists(file)) && (await fs.readFile(file, 'utf8')) === content) return false;
  await fs.ensureDir(path.dirname(file));
  await fs.writeFile(file, content);
  return true;
};

/** Generate the screen files into the staged app. Returns whether any file changed. */
export const generateScreens = async (
  context: ScreensContext,
  appPath: string
): Promise<{ manifest: ScreensManifest; changed: boolean }> => {
  const { files, manifest } = await readScreens(context);
  const generatedDir = path.resolve(appPath, 'generated');
  const results = await Promise.all([
    writeIfChanged(path.resolve(appPath, SCREENS_MANIFEST_PATH), `${JSON.stringify(manifest, null, 2)}\n`),
    writeIfChanged(path.resolve(appPath, SCREENS_CLIENT_PATH), clientSource(files, generatedDir)),
    writeIfChanged(path.resolve(appPath, SCREENS_SERVER_PATH), serverSource(files, generatedDir)),
    writeIfChanged(path.resolve(appPath, SCREENS_STYLES_PATH), stylesSource(files, generatedDir)),
  ]);
  return { manifest, changed: results.some(Boolean) };
};

export { ScreenBuildError };
